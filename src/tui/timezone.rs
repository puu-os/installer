const TICK: Duration = Duration::from_millis(80);
/// Quiet period after the last keypress before the UTC offset is (re)computed.
const OFFSET_DEBOUNCE: Duration = Duration::from_millis(250);
const VIEW_LON_SPAN: f64 = 180.0;
const PAN_PAGE_FRACTION: f64 = 0.5;
const SEA_DEEP: Color = Color::Indexed(4);
const SEA_SHIMMER: Color = Color::Indexed(12);
const LAND_COAST: Color = Color::Indexed(10);
const PIN_BG: Color = Color::Indexed(1);
const GUIDE: Color = Color::Indexed(7);
const GUIDE_STRONG: Color = Color::Indexed(14);

/// Latitude band shown by the map. The poles are cropped (mostly empty ocean
/// and the featureless Antarctic ice) so the inhabited band — where every
/// timezone actually lives — gets more rows and is easier to read.
const LAT_MIN: f64 = -60.0;
const LAT_MAX: f64 = 78.0;

/// A selectable timezone with its representative location.
#[derive(Clone)]
pub(crate) struct Zone {
    pub name: String,
    pub lat: f64,
    pub lon: f64,
    pub has_coord: bool,
}

/// IANA tz database `zone1970.tab`, vendored verbatim (tzdb release 2026b).
/// See <https://data.iana.org/time-zones/>.
const ZONE_TAB: &str = include_str!("zone1970.tab");

/// 1-bit land/sea raster (Natural Earth 1:110m land, public domain) in plate
/// carrée projection: `MAP_W` x `MAP_H` cells, top row = +90 deg, left column
/// = -180 deg, MSB-first bits, whole bytes per row. A set bit is land. The
/// mask is generated by `scripts/gen_world_mask.py` and embedded at build
/// time, so the installer needs no runtime map data or GIS dependency.
const WORLD_MASK: &[u8] = include_bytes!("world_mask.bin");
const MAP_W: usize = 720;
const MAP_H: usize = 360;
const ROW_BYTES: usize = MAP_W / 8;

/// Parse one `zone1970.tab` data row (`codes \t coord \t name \t comment`) into a
/// `Zone`. Returns `None` for comment/blank/short lines. The coordinate is a
/// compact ISO 6709 pair (`±DDMM±DDDMM` / `±DDMMSS±DDDMMSS`).
fn parse_zone_line(line: &str) -> Option<Zone> {
    let line = line.trim_end();
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    let mut cols = line.split('\t');
    let _codes = cols.next()?;
    let coord = cols.next()?;
    let name = cols.next()?;
    let c = iso6709parse::parse_string_representation::<iso6709parse::ISO6709Coord>(coord).ok()?;
    Some(Zone {
        name: name.to_string(),
        lat: c.lat,
        lon: c.lon,
        has_coord: true,
    })
}

/// Build the timezone list from the embedded `zone1970.tab`. `UTC` (absent from
/// tzdata's zone table) is injected and pinned first; the rest are sorted A-to-Z
/// by name (the table itself is grouped by country code, not name).
pub(crate) fn load_zones() -> Vec<Zone> {
    let mut rest: Vec<Zone> = ZONE_TAB.lines().filter_map(parse_zone_line).collect();
    rest.sort_by(|a, b| a.name.cmp(&b.name));
    let mut zones = Vec::with_capacity(rest.len() + 1);
    zones.push(Zone {
        name: "UTC".to_string(),
        lat: 0.0,
        lon: 0.0,
        has_coord: false,
    });
    zones.extend(rest);
    zones
}

/// Land/sea lookup against the embedded raster. Longitude wraps at ±180 deg so
/// the date-line seam never produces a blank edge.
fn is_land(lon: f64, lat: f64) -> bool {
    let fx = ((lon + 180.0).rem_euclid(360.0) / 360.0 * MAP_W as f64) as usize;
    let fy = ((90.0 - lat) / 180.0 * MAP_H as f64).clamp(0.0, (MAP_H - 1) as f64) as usize;
    let x = fx.min(MAP_W - 1);
    let byte = WORLD_MASK[fy * ROW_BYTES + x / 8];
    byte & (0x80 >> (x % 8)) != 0
}

/// Format a `date +%z` value like `+0200` as `UTC+2` / `UTC+5:30` (empty on failure).
fn format_offset(raw: &str) -> Option<String> {
    let bytes = raw.as_bytes();
    if bytes.len() != 5 {
        return None;
    }
    let sign = raw.as_bytes()[0] as char;
    if sign != '+' && sign != '-' {
        return None;
    }
    let hours: i32 = raw.get(1..3)?.parse().ok()?;
    let minutes: i32 = raw.get(3..5)?.parse().ok()?;
    if hours == 0 && minutes == 0 {
        return Some("UTC".to_string());
    }
    if minutes == 0 {
        Some(format!("UTC{sign}{hours}"))
    } else {
        Some(format!("UTC{sign}{hours}:{minutes:02}"))
    }
}

/// Ask the system `date` for a zone's current UTC offset. Cosmetic; empty if
/// `date` is missing or fails.
fn tz_offset(name: &str) -> String {
    std::process::Command::new("date")
        .env("TZ", name)
        .arg("+%z")
        .output()
        .ok()
        .filter(|o| o.status.success())
        .and_then(|o| format_offset(String::from_utf8_lossy(&o.stdout).trim()))
        .unwrap_or_default()
}

fn wrap_lon(lon: f64) -> f64 {
    (lon + 180.0).rem_euclid(360.0) - 180.0
}

fn lon_delta(from: f64, to: f64) -> f64 {
    wrap_lon(to - from)
}

fn format_lon(lon: f64) -> String {
    let lon = wrap_lon(lon);
    let deg = lon.abs().round() as i32;
    let hemi = if lon < 0.0 { 'W' } else { 'E' };
    format!("{deg}{hemi}")
}

struct MapLayout {
    overview_y: u16,
    top_marker_y: u16,
    map_y: u16,
    map_h: u16,
    bottom_marker_y: u16,
    filter_y: u16,
    list_top: u16,
    list_h: u16,
}

/// Vertical layout of the timezone screen.
fn layout(height: u16) -> MapLayout {
    let bottom = height.saturating_sub(1);
    let content = bottom.saturating_sub(2);
    let max_map = content.saturating_sub(3 + 1 + 3).max(1);
    let map_h = (height * 11 / 20).clamp(1, max_map);
    let overview_y = 2;
    let top_marker_y = overview_y + 1;
    let map_y = top_marker_y + 1;
    let bottom_marker_y = map_y + map_h;
    let filter_y = bottom_marker_y + 1;
    let list_top = filter_y + 1;
    let list_h = bottom.saturating_sub(list_top).max(1);
    MapLayout {
        overview_y,
        top_marker_y,
        map_y,
        map_h,
        bottom_marker_y,
        filter_y,
        list_top,
        list_h,
    }
}

struct MapView {
    center_lon: f64,
}

impl MapView {
    fn new(selected: Option<&Zone>) -> Self {
        let mut view = Self { center_lon: 0.0 };
        if let Some(zone) = selected {
            view.follow(zone);
        }
        view
    }

    fn follow(&mut self, zone: &Zone) {
        if zone.has_coord {
            self.center_lon = wrap_lon(zone.lon);
        }
    }

    fn pan(&mut self, delta: f64) {
        self.center_lon = wrap_lon(self.center_lon + delta);
    }

    fn recenter(&mut self, zone: Option<&Zone>) {
        if let Some(zone) = zone {
            self.follow(zone);
        }
    }

    fn page_pan(&mut self, direction: f64) {
        self.pan(VIEW_LON_SPAN * PAN_PAGE_FRACTION * direction);
    }

    fn start_lon(&self) -> f64 {
        wrap_lon(self.center_lon - VIEW_LON_SPAN / 2.0)
    }

    fn end_lon(&self) -> f64 {
        wrap_lon(self.center_lon + VIEW_LON_SPAN / 2.0)
    }

    fn lon_at(&self, x: usize, width: usize) -> f64 {
        wrap_lon(self.start_lon() + (x as f64 + 0.5) / width.max(1) as f64 * VIEW_LON_SPAN)
    }

    fn zone_x(&self, zone: &Zone, width: usize) -> Option<isize> {
        if !zone.has_coord || width == 0 {
            return None;
        }
        let delta = lon_delta(self.center_lon, zone.lon);
        let raw = ((delta + VIEW_LON_SPAN / 2.0) / VIEW_LON_SPAN * width as f64).floor() as isize;
        Some(raw)
    }
}

/// The scrollable, type-to-filter picker state. `sel`/`top` index into `filtered`.
struct TzPick {
    all: Vec<Zone>,
    filter: String,
    filtered: Vec<usize>,
    sel: usize,
    top: usize,
    last_input: Instant,
    offset_zone: String,
    offset_str: String,
}

impl TzPick {
    fn new(all: Vec<Zone>, current: &str) -> Self {
        let filtered: Vec<usize> = (0..all.len()).collect();
        let sel = filtered
            .iter()
            .position(|&i| all[i].name == current)
            .unwrap_or(0);
        Self {
            all,
            filter: String::new(),
            filtered,
            sel,
            top: 0,
            last_input: Instant::now(),
            offset_zone: String::new(),
            offset_str: String::new(),
        }
    }

    fn selected(&self) -> Option<&Zone> {
        self.filtered.get(self.sel).map(|&i| &self.all[i])
    }

    fn refilter(&mut self) {
        let needle = self.filter.to_ascii_lowercase();
        let keep = self.filtered.get(self.sel).copied();
        self.filtered = self
            .all
            .iter()
            .enumerate()
            .filter(|(_, z)| needle.is_empty() || z.name.to_ascii_lowercase().contains(&needle))
            .map(|(i, _)| i)
            .collect();
        self.sel = keep
            .and_then(|k| self.filtered.iter().position(|&i| i == k))
            .unwrap_or(0);
        if self.filtered.is_empty() {
            self.sel = 0;
        } else if self.sel >= self.filtered.len() {
            self.sel = self.filtered.len() - 1;
        }
        self.top = self.top.min(self.sel);
    }

    fn move_up(&mut self) {
        if !self.filtered.is_empty() {
            self.sel = self.sel.checked_sub(1).unwrap_or(self.filtered.len() - 1);
            self.last_input = Instant::now();
        }
    }

    fn move_down(&mut self) {
        if !self.filtered.is_empty() {
            self.sel = (self.sel + 1) % self.filtered.len();
            self.last_input = Instant::now();
        }
    }

    fn push_filter(&mut self, c: char) {
        self.filter.push(c);
        self.refilter();
        self.last_input = Instant::now();
    }

    fn backspace(&mut self) {
        self.filter.pop();
        self.refilter();
        self.last_input = Instant::now();
    }

    /// Keep the selected row inside a `visible`-row window.
    fn reframe(&mut self, visible: usize) {
        if self.filtered.is_empty() || visible == 0 {
            self.top = 0;
            return;
        }
        self.top = self.top.min(self.sel);
        if self.sel >= self.top + visible {
            self.top = self.sel + 1 - visible;
        }
    }

    fn on_tick(&mut self, now: Instant) {
        if now.duration_since(self.last_input) > OFFSET_DEBOUNCE {
            self.update_offset();
        }
    }

    fn update_offset(&mut self) {
        let Some(name) = self.selected().map(|z| z.name.clone()) else {
            return;
        };
        if name != self.offset_zone {
            self.offset_str = tz_offset(&name);
            self.offset_zone = name;
        }
    }
}

fn draw_marker_row(f: &mut Frame, view: &MapView, zone: Option<&Zone>, rect: Rect, top: bool) {
    let buf = f.buffer_mut();
    let width = rect.width.max(1) as usize;
    for cx in 0..width {
        if let Some(cell) = buf.cell_mut((rect.x + cx as u16, rect.y)) {
            cell.set_char(' ').set_fg(ACCENT).set_bg(SEA);
        }
    }
    let Some(zone) = zone else {
        return;
    };
    let Some(raw_x) = view.zone_x(zone, width) else {
        return;
    };
    if raw_x < 0 {
        for dx in 0..width.min(3) {
            if let Some(cell) = buf.cell_mut((rect.x + dx as u16, rect.y)) {
                cell.set_char('<').set_fg(WARN).set_bg(SEA);
            }
        }
        return;
    }
    if raw_x >= width as isize {
        for dx in 0..width.min(3) {
            let x = rect.x + width as u16 - 1 - dx as u16;
            if let Some(cell) = buf.cell_mut((x, rect.y)) {
                cell.set_char('>').set_fg(WARN).set_bg(SEA);
            }
        }
        return;
    }
    let x = raw_x as u16;
    let ch = if top { 'v' } else { '^' };
    if let Some(cell) = buf.cell_mut((rect.x + x, rect.y)) {
        cell.set_char(ch).set_fg(WARN).set_bg(SEA);
    }
}

enum CellKind {
    Sea,
    Coast,
    Land,
}

fn classify_cell(
    lon: f64,
    lat_top: f64,
    lat_bot: f64,
    lon_step: f64,
) -> (CellKind, char, Color, Color) {
    let top = is_land(lon, lat_top);
    let bot = is_land(lon, lat_bot);
    let left_top = is_land(lon - lon_step, lat_top);
    let left_bot = is_land(lon - lon_step, lat_bot);
    let right_top = is_land(lon + lon_step, lat_top);
    let right_bot = is_land(lon + lon_step, lat_bot);
    let neighbors = [left_top, left_bot, right_top, right_bot];
    let touches_land = top || bot;
    let touches_sea = !top || !bot;
    let edge =
        neighbors.iter().any(|&land| land != top) || neighbors.iter().any(|&land| land != bot);
    let ch = match (top, bot) {
        (true, true) => '\u{2588}',
        (true, false) => '\u{2580}',
        (false, true) => '\u{2584}',
        (false, false) => ' ',
    };
    if touches_land && (touches_sea || edge) {
        (CellKind::Coast, ch, LAND_COAST, SEA_SHIMMER)
    } else if touches_land {
        (CellKind::Land, ch, LAND, SEA_DEEP)
    } else {
        (CellKind::Sea, ch, LAND, SEA_DEEP)
    }
}

fn sea_bg_for_row(cy: usize) -> Color {
    if cy % 6 < 2 { SEA_SHIMMER } else { SEA_DEEP }
}

fn near_lon(lon: f64, target: f64, step: f64) -> bool {
    lon_delta(lon, target).abs() <= step * 0.5
}

fn near_lat(lat: f64, target: f64, step: f64) -> bool {
    (lat - target).abs() <= step * 0.5
}

fn draw_overview_row(f: &mut Frame, view: &MapView, zone: Option<&Zone>, rect: Rect) {
    let buf = f.buffer_mut();
    let width = rect.width.max(1) as usize;
    for cx in 0..width {
        let world_lon = -180.0 + (cx as f64 + 0.5) / width as f64 * 360.0;
        let in_view = lon_delta(view.center_lon, world_lon).abs() < VIEW_LON_SPAN / 2.0;
        let ch = if in_view { '=' } else { '·' };
        let fg = if in_view { GUIDE_STRONG } else { ACCENT };
        if let Some(cell) = buf.cell_mut((rect.x + cx as u16, rect.y)) {
            cell.set_char(ch).set_fg(fg).set_bg(SEA);
        }
    }
    if let Some(zone) = zone.filter(|z| z.has_coord) {
        let x = (((wrap_lon(zone.lon) + 180.0) / 360.0) * width as f64)
            .floor()
            .clamp(0.0, width.saturating_sub(1) as f64) as u16;
        if let Some(cell) = buf.cell_mut((rect.x + x, rect.y)) {
            cell.set_char('*').set_fg(WARN).set_bg(SEA);
        }
    }
}

/// Draw the filled world map into `rect`. Each terminal cell holds two raster
/// sub-rows, so a cell is one of `▀` `▄` `█` ` ` with the foreground painted
/// land-coloured over a sea-coloured background. The visible viewport spans
/// half the globe, which doubles the horizontal sampling density and can be
/// panned left/right.
fn draw_map(f: &mut Frame, pick: &TzPick, view: &MapView, rect: Rect) {
    let buf = f.buffer_mut();
    let width = rect.width.max(1) as usize;
    let height = rect.height.max(1) as usize;
    let total_sub = height * 2;
    let span = LAT_MAX - LAT_MIN;

    let lon_step = VIEW_LON_SPAN / width.max(1) as f64;
    let lat_step = span / total_sub as f64;
    let selected_lon = pick.selected().filter(|z| z.has_coord).map(|z| z.lon);
    for cy in 0..height {
        let lat_top = LAT_MAX - (2.0 * cy as f64 + 0.5) / total_sub as f64 * span;
        let lat_bot = LAT_MAX - (2.0 * cy as f64 + 1.5) / total_sub as f64 * span;
        let lat_mid = (lat_top + lat_bot) * 0.5;
        let sea_bg = sea_bg_for_row(cy);
        let equator_here = near_lat(lat_mid, 0.0, lat_step * 2.0);
        for cx in 0..width {
            let lon = view.lon_at(cx, width);
            let (kind, mut ch, mut fg, bg) = classify_cell(lon, lat_top, lat_bot, lon_step);
            let x = rect.x + cx as u16;
            let y = rect.y + cy as u16;
            let major_meridian = near_lon(lon, 0.0, lon_step) || near_lon(lon, 90.0, lon_step);
            let zone_meridian = selected_lon.is_some_and(|target| near_lon(lon, target, lon_step));
            if let Some(cell) = buf.cell_mut((x, y)) {
                let bg = match kind {
                    CellKind::Sea => sea_bg,
                    CellKind::Coast => bg,
                    CellKind::Land => bg,
                };
                if major_meridian && matches!(kind, CellKind::Sea) {
                    ch = '·';
                    fg = GUIDE;
                }
                if equator_here && matches!(kind, CellKind::Sea) {
                    ch = '─';
                    fg = GUIDE;
                }
                if zone_meridian {
                    ch = '│';
                    fg = if equator_here { GUIDE_STRONG } else { WARN };
                }
                if major_meridian && equator_here && !zone_meridian {
                    ch = '┼';
                    fg = GUIDE_STRONG;
                }
                cell.set_char(ch).set_fg(fg).set_bg(bg);
            }
        }
    }

    let Some(z) = pick.selected() else {
        return;
    };
    if !z.has_coord {
        return;
    }
    let lat = z.lat.clamp(LAT_MIN, LAT_MAX);
    let raw_x = view.zone_x(z, width).unwrap_or(0);
    let cx = raw_x.clamp(0, width as isize - 1) as usize;
    let msub = ((LAT_MAX - lat) / span * total_sub as f64) as isize;
    let cy = (msub / 2).clamp(0, height as isize - 1) as usize;

    let mut mark = |dx: i32, dy: i32, ch: char| {
        let x = cx as i32 + dx;
        let y = cy as i32 + dy;
        if !(0..width as i32).contains(&x) || !(0..height as i32).contains(&y) {
            return;
        }
        let cell = buf.cell_mut((rect.x + x as u16, rect.y + y as u16));
        if let Some(cell) = cell {
            cell.set_char(ch).set_fg(WARN).set_bg(PIN_BG);
        }
    };
    mark(0, 0, '\u{2588}');
    mark(0, -1, '\u{2584}');
    mark(0, 1, '\u{2580}');
    mark(-1, 0, '\u{2588}');
    mark(1, 0, '\u{2588}');
}

/// Render the whole timezone screen (map band, filter line, scroll list).
fn draw_timezone(f: &mut Frame, pick: &TzPick, view: &MapView, subtitle: &str) {
    Installer::draw_frame(
        f,
        "Select Time Zone",
        subtitle,
        "Type filter, Up/Down select, Left/Right pan, Home/. recenter, Enter confirm, Esc back",
    );
    let area = f.area();
    let layout = layout(area.height);

    draw_overview_row(
        f,
        view,
        pick.selected(),
        Rect::new(0, layout.overview_y, area.width, 1),
    );

    draw_marker_row(
        f,
        view,
        pick.selected(),
        Rect::new(0, layout.top_marker_y, area.width, 1),
        true,
    );
    if layout.map_h > 0 {
        draw_map(
            f,
            pick,
            view,
            Rect::new(0, layout.map_y, area.width, layout.map_h),
        );
    }
    draw_marker_row(
        f,
        view,
        pick.selected(),
        Rect::new(0, layout.bottom_marker_y, area.width, 1),
        false,
    );

    f.render_widget(
        Paragraph::new(format!(" Filter: {}_", pick.filter)).style(Style::default().fg(ACCENT)),
        Rect::new(0, layout.filter_y, area.width, 1),
    );

    if pick.filtered.is_empty() {
        f.render_widget(
            Paragraph::new("  No matching time zones").style(Style::default().fg(ERR)),
            Rect::new(0, layout.list_top, area.width, 1),
        );
        return;
    }

    let visible = layout.list_h as usize;
    let end = (pick.top + visible).min(pick.filtered.len());
    for (row, &idx) in pick.filtered[pick.top..end].iter().enumerate() {
        let i = pick.top + row;
        let is_sel = i == pick.sel;
        let marker_ch = if is_sel { ">" } else { " " };
        f.render_widget(
            Paragraph::new(format!("{marker_ch} {}", pick.all[idx].name))
                .style(highlight_style(is_sel)),
            Rect::new(0, layout.list_top + row as u16, area.width, 1),
        );
    }
}

impl Installer {
    #[allow(clippy::too_many_lines)]
    pub(crate) fn timezone_screen(
        &mut self,
        term: &mut Terminal<CrosstermBackend<io::Stdout>>,
    ) -> ScreenAction {
        let current = self.ctx.config.identity.timezone.clone();
        let mut pick = TzPick::new(load_zones(), &current);
        pick.update_offset();
        let mut view = MapView::new(pick.selected());

        let mut last_tick = Instant::now();

        loop {
            let height = term.size().map_or(24, |s| s.height);
            let layout = layout(height);
            pick.reframe(layout.list_h as usize);

            let viewport = format!(
                "view {}..{}",
                format_lon(view.start_lon()),
                format_lon(view.end_lon())
            );
            let subtitle = match pick.selected() {
                Some(z) if pick.offset_str.is_empty() => format!("{}   {viewport}", z.name),
                Some(z) => format!("{}   {}   {viewport}", z.name, pick.offset_str),
                None => viewport,
            };

            term.draw(|f| draw_timezone(f, &pick, &view, &subtitle))
                .ok();

            let timeout = TICK.saturating_sub(last_tick.elapsed());
            if event::poll(timeout).unwrap_or(false) {
                if let Ok(Event::Key(key)) = event::read() {
                    match key.code {
                        KeyCode::Esc => return ScreenAction::Back,
                        KeyCode::Enter => {
                            if let Some(z) = pick.selected() {
                                self.ctx.config.identity.timezone.clone_from(&z.name);
                                return ScreenAction::Continue;
                            }
                        }
                        KeyCode::Up => {
                            pick.move_up();
                            if let Some(zone) = pick.selected() {
                                view.follow(zone);
                            }
                        }
                        KeyCode::Down => {
                            pick.move_down();
                            if let Some(zone) = pick.selected() {
                                view.follow(zone);
                            }
                        }
                        KeyCode::Left => view.page_pan(-1.0),
                        KeyCode::Right => view.page_pan(1.0),
                        KeyCode::Home | KeyCode::Char('.') => view.recenter(pick.selected()),
                        KeyCode::Backspace => {
                            pick.backspace();
                            if let Some(zone) = pick.selected() {
                                view.follow(zone);
                            }
                        }
                        KeyCode::Char('u') if key.modifiers.contains(KeyModifiers::CONTROL) => {
                            pick.filter.clear();
                            pick.refilter();
                            pick.last_input = Instant::now();
                            if let Some(zone) = pick.selected() {
                                view.follow(zone);
                            }
                        }
                        KeyCode::Char(c)
                            if c.is_ascii()
                                && c >= ' '
                                && !key.modifiers.contains(KeyModifiers::CONTROL) =>
                        {
                            pick.push_filter(c);
                            if let Some(zone) = pick.selected() {
                                view.follow(zone);
                            }
                        }
                        _ => {}
                    }
                }
            }

            if last_tick.elapsed() >= TICK {
                pick.on_tick(Instant::now());
                last_tick = Instant::now();
            }
        }
    }
}
